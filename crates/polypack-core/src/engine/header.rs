//! C 头文件生成器（T-M6-02）：唯一来源是 [`super::ffi`] 的接口清单。
//!
//! 生成物 `include/polypack_engine.h` 入库；`tests/cffi.rs` 断言它与
//! [`c_header`] 逐字节一致（漂移即红），并在 gcc / clang 下真编译。
//! 打包器与四端（QNX / AUTOSAR / VxWorks / Zephyr / FreeRTOS）通过
//! [`write_header`] 取同一份头文件，不另写。

use std::path::{Path, PathBuf};

use super::ffi::{ABI_VERSION, FFI_CONSTANTS, FFI_FUNCTIONS};

/// 头文件名（所有端统一）。
pub const HEADER_FILE: &str = "polypack_engine.h";

/// C 声明里的「类型 + 名字」拼接：指针类型的 `*` 贴名字（`char *text`）。
fn declarator(ty: &str, name: &str) -> String {
    if ty.ends_with('*') {
        format!("{ty}{name}")
    } else {
        format!("{ty} {name}")
    }
}

/// 生成 C 头文件文本。
pub fn c_header() -> String {
    let mut text = String::new();
    text.push_str("/* Generated by crates/polypack-core/src/engine/header.rs from the single ABI\n");
    text.push_str(" * definition in crates/polypack-core/src/engine/ffi.rs. DO NOT EDIT.\n");
    text.push_str(" *\n");
    text.push_str(&format!(
        " * PolyPack engine layer C ABI (polypack_engine_*), ABI version {ABI_VERSION}.\n"
    ));
    text.push_str(" * Consumers: QNX / AUTOSAR Adaptive / VxWorks / Zephyr / FreeRTOS.\n");
    text.push_str(" */\n");
    text.push_str("#ifndef POLYPACK_ENGINE_H\n#define POLYPACK_ENGINE_H\n\n");
    text.push_str("#include <stddef.h>\n#include <stdint.h>\n\n");
    text.push_str(&format!(
        "#define POLYPACK_ENGINE_ABI_VERSION {ABI_VERSION}\n\n"
    ));
    for constant in FFI_CONSTANTS {
        text.push_str(&format!(
            "/* {} */\n#define {} {}\n",
            constant.doc, constant.name, constant.value
        ));
    }
    text.push_str("\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");
    for function in FFI_FUNCTIONS {
        text.push_str(&format!("/* {} */\n", function.doc));
        let params = if function.params.is_empty() {
            "void".to_string()
        } else {
            function
                .params
                .iter()
                .map(|(name, ty)| declarator(ty, name))
                .collect::<Vec<_>>()
                .join(", ")
        };
        text.push_str(&format!(
            "{}({});\n\n",
            declarator(function.returns, function.name),
            params
        ));
    }
    text.push_str("#ifdef __cplusplus\n}\n#endif\n\n#endif /* POLYPACK_ENGINE_H */\n");
    text
}

/// 把生成的头文件写到 `dir/polypack_engine.h`（打包器 / 四端接入的最小面）。
pub fn write_header(dir: &Path) -> std::io::Result<PathBuf> {
    std::fs::create_dir_all(dir)?;
    let path = dir.join(HEADER_FILE);
    std::fs::write(&path, c_header())?;
    Ok(path)
}
