//! M9-E1 验收（CLI 侧）：`poly verify --sbom` 的三件套、确定性与产物/材料摘要。
//!
//! 用 `web` 静态站做夹具：打包暂存目录里放一份 `site/`（与 StaticSite 打包器同布局），
//! 不依赖任何外部打包工具。`--sbom` 对暂存产物生成 SPDX 2.3 / CycloneDX 1.5 /
//! in-toto provenance；两次生成必须字节一致，缺产物必须告警跳过而非静默假绿。

use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicUsize, Ordering};

use serde_json::Value;
use sha2::{Digest as _, Sha256};

/// 最小工程配置：不声明 `[targets.*]`，用官方 `web` 目标。
const CONFIG: &str = "[package]\nname = \"SBOM Fixture\"\nversion = \"0.1.2\"\n\
[ui]\nframework = \"react\"\nentry = \"index.html\"\n[core]\ncrate = \"core\"\n";

/// 核心 crate：一个 path 依赖，足以验证依赖图与 `Cargo.lock` 对齐。
const CORE_MANIFEST: &str = "[package]\nname = \"fixture-core\"\nversion = \"0.1.2\"\n\
edition = \"2021\"\n\n[workspace]\n\n[dependencies]\nfixture-dep = { path = \"dep\" }\n";
const DEP_MANIFEST: &str =
    "[package]\nname = \"fixture-dep\"\nversion = \"0.0.2\"\nedition = \"2021\"\n";
const CORE_LOCK: &str = "# This file is automatically @generated by Cargo.\n\
# It is not intended for manual editing.\nversion = 4\n\n\
[[package]]\nname = \"fixture-core\"\nversion = \"0.1.2\"\ndependencies = [\n \"fixture-dep\",\n]\n\n\
[[package]]\nname = \"fixture-dep\"\nversion = \"0.0.2\"\n";
const SOURCE_TREE_EXCLUDES: [&str; 4] = ["target", ".polypack", ".git", "node_modules"];

static COUNTER: AtomicUsize = AtomicUsize::new(0);

struct TempDir(PathBuf);

impl TempDir {
    fn new(tag: &str) -> Self {
        let path = std::env::temp_dir().join(format!(
            "polypack-sbom-{tag}-{}-{}",
            std::process::id(),
            COUNTER.fetch_add(1, Ordering::Relaxed)
        ));
        let _ = std::fs::remove_dir_all(&path);
        std::fs::create_dir_all(&path).expect("临时目录可创建");
        Self(path)
    }

    fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn write_fixture(root: &Path, with_artifact: bool) {
    std::fs::write(root.join("polypack.toml"), CONFIG).expect("写配置");
    let core = root.join("core");
    let dep = core.join("dep");
    std::fs::create_dir_all(core.join("src")).expect("建 core/src");
    std::fs::create_dir_all(dep.join("src")).expect("建 dep/src");
    std::fs::write(core.join("Cargo.toml"), CORE_MANIFEST).expect("写 core 清单");
    std::fs::write(core.join("Cargo.lock"), CORE_LOCK).expect("写 lock");
    std::fs::write(core.join("src/lib.rs"), "pub fn f() {}\n").expect("写 core 源");
    std::fs::write(dep.join("Cargo.toml"), DEP_MANIFEST).expect("写 dep 清单");
    std::fs::write(dep.join("src/lib.rs"), "pub fn g() {}\n").expect("写 dep 源");
    if with_artifact {
        let site = root.join(".polypack/packages/web/site");
        std::fs::create_dir_all(&site).expect("建暂存站点");
        std::fs::write(
            site.join("index.html"),
            "<!doctype html>\n<html lang=\"zh\"><body>sbom</body></html>\n",
        )
        .expect("写站点入口");
    }
}

fn poly(args: &[&str], cwd: &Path) -> Output {
    Command::new(env!("CARGO_BIN_EXE_poly"))
        .args(args)
        .current_dir(cwd)
        .env("POLYPACK_BUILDER", "sbom-test-builder")
        .env_remove("SOURCE_DATE_EPOCH")
        .output()
        .expect("poly 可执行")
}

fn stderr(out: &Output) -> String {
    String::from_utf8_lossy(&out.stderr).into_owned()
}

fn json_lines(out: &Output) -> Vec<Value> {
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .filter(|line| !line.trim().is_empty())
        .map(|line| serde_json::from_str(line).expect("stdout 每行应为合法 JSON"))
        .collect()
}

fn read_files(dir: &Path) -> Vec<(String, Vec<u8>)> {
    let mut files: Vec<(String, Vec<u8>)> = std::fs::read_dir(dir)
        .expect("SBOM 目录存在")
        .map(|entry| entry.expect("目录项可读"))
        .map(|entry| {
            (
                entry.file_name().to_string_lossy().into_owned(),
                std::fs::read(entry.path()).expect("SBOM 可读"),
            )
        })
        .collect();
    files.sort_by(|a, b| a.0.cmp(&b.0));
    files
}

fn file<'a>(files: &'a [(String, Vec<u8>)], name: &str) -> &'a [u8] {
    files
        .iter()
        .find(|(file_name, _)| file_name == name)
        .map(|(_, bytes)| bytes.as_slice())
        .unwrap_or_else(|| panic!("缺 {name}：{files:?}"))
}

fn sha256_hex(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

#[test]
fn sbom_is_deterministic_and_matches_artifact_and_materials() {
    let temp = TempDir::new("deterministic");
    write_fixture(temp.path(), true);
    let out_dir = temp.path().join(".polypack/sbom/web");
    let site = temp.path().join(".polypack/packages/web/site");

    let first = poly(
        &["verify", "--sbom", "--target", "web", "--json"],
        temp.path(),
    );
    assert_eq!(
        first.status.code(),
        Some(0),
        "有暂存产物时 --sbom 应成功：{}",
        stderr(&first)
    );
    let files = read_files(&out_dir);
    let names: Vec<&str> = files.iter().map(|(name, _)| name.as_str()).collect();
    assert_eq!(
        names,
        ["site.cdx.json", "site.intoto.jsonl", "site.spdx.json"],
        "每个产物三项，文件名以产物为前缀"
    );
    let lines = json_lines(&first);
    assert!(
        lines
            .iter()
            .any(|line| line["event"] == "verified" && line["checker"] == "sbom-spdx"),
        "SBOM 生成须发 verified 事件：{lines:?}"
    );

    let spdx: Value = serde_json::from_slice(file(&files, "site.spdx.json")).expect("SPDX JSON");
    assert_eq!(spdx["spdxVersion"], "SPDX-2.3");
    let packages: Vec<&str> = spdx["packages"]
        .as_array()
        .expect("packages")
        .iter()
        .filter_map(|package| package["name"].as_str())
        .collect();
    assert!(
        packages.contains(&"fixture-core"),
        "依赖图含 workspace 包：{packages:?}"
    );
    assert!(
        packages.contains(&"fixture-dep"),
        "依赖图含 path 依赖：{packages:?}"
    );

    let cdx: Value = serde_json::from_slice(file(&files, "site.cdx.json")).expect("CDX JSON");
    assert_eq!(cdx["specVersion"], "1.5");
    let components: Vec<&str> = cdx["components"]
        .as_array()
        .expect("components")
        .iter()
        .filter_map(|component| component["name"].as_str())
        .collect();
    assert!(
        components.contains(&"fixture-dep"),
        "CycloneDX 含依赖：{components:?}"
    );

    let text = String::from_utf8(file(&files, "site.intoto.jsonl").to_vec()).expect("JSONL UTF-8");
    let records: Vec<&str> = text
        .lines()
        .filter(|line| !line.trim().is_empty())
        .collect();
    assert_eq!(records.len(), 1, "provenance 是单行 in-toto Statement");
    let provenance: Value = serde_json::from_str(records[0]).expect("provenance JSON");
    assert_eq!(provenance["_type"], "https://in-toto.io/Statement/v1");
    assert_eq!(
        provenance["predicateType"],
        "https://slsa.dev/provenance/v1"
    );
    let subject = &provenance["subject"][0];
    assert_eq!(subject["name"], "site");
    let expected = poly_cache::Digest::of_tree(&site, &[]).expect("产物树摘要");
    assert_eq!(
        subject["digest"]["blake3"],
        expected.to_string(),
        "subject 摘要须等于暂存产物树摘要"
    );
    assert!(
        subject["digest"].get("sha256").is_none(),
        "目录产物没有整文件 sha256"
    );
    assert_eq!(
        provenance["predicate"]["runDetails"]["builder"]["id"],
        "sbom-test-builder"
    );
    assert!(
        provenance["predicate"]["buildDefinition"]["internalParameters"]["polypackNotice"]
            .as_str()
            .is_some_and(|notice| notice.contains("not a SLSA certification")),
        "provenance 不得自称 SLSA 认证"
    );

    let materials = provenance["predicate"]["buildDefinition"]["resolvedDependencies"]
        .as_array()
        .expect("materials");
    let find = |uri: &str| {
        materials
            .iter()
            .find(|material| material["uri"] == uri)
            .unwrap_or_else(|| panic!("materials 缺 {uri}：{materials:?}"))
    };
    let lock_bytes = std::fs::read(temp.path().join("core/Cargo.lock")).expect("读 lock");
    assert_eq!(
        find("Cargo.lock")["digest"]["sha256"],
        sha256_hex(&lock_bytes)
    );
    let source_tree =
        poly_cache::Digest::of_tree(temp.path(), &SOURCE_TREE_EXCLUDES).expect("源树摘要");
    assert_eq!(
        find("source-tree")["digest"]["blake3"],
        source_tree.to_string()
    );

    let second = poly(
        &["verify", "--sbom", "--target", "web", "--json"],
        temp.path(),
    );
    assert_eq!(second.status.code(), Some(0), "二跑：{}", stderr(&second));
    assert_eq!(files, read_files(&out_dir), "两次生成的字节必须一致");
}

#[test]
fn verify_without_sbom_keeps_existing_behavior() {
    let temp = TempDir::new("no-flag");
    write_fixture(temp.path(), true);
    let out = poly(&["verify", "--target", "web", "--json"], temp.path());
    assert_eq!(
        out.status.code(),
        Some(1),
        "web 的校验器未接入，现有语义必须保持非零：{}",
        stderr(&out)
    );
    assert!(stderr(&out).contains("poly::E_VERIFY_0002"));
    assert!(
        !temp.path().join(".polypack/sbom").exists(),
        "没有 --sbom 不得写任何 SBOM"
    );
}

#[test]
fn missing_artifact_is_an_explicit_skip() {
    let temp = TempDir::new("missing");
    write_fixture(temp.path(), false);
    let out = poly(
        &["verify", "--sbom", "--target", "web", "--json"],
        temp.path(),
    );
    assert_eq!(
        out.status.code(),
        Some(1),
        "缺产物不得假绿：{}",
        stderr(&out)
    );
    let diagnostics = stderr(&out);
    assert!(diagnostics.contains("poly::E_VERIFY_0002"), "{diagnostics}");
    let lines = json_lines(&out);
    assert!(
        lines.iter().any(|line| {
            line["event"] == "warning"
                && line["message"].as_str().is_some_and(|message| {
                    message.contains("web") && message.contains("没有暂存产物")
                })
        }),
        "缺产物须逐目标告警说明：{lines:?}"
    );
    assert!(
        !temp.path().join(".polypack/sbom").exists(),
        "缺产物时不应留下 SBOM"
    );
}
